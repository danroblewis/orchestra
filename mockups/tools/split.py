"""Split a capture (capture.cjs) into the mockups' fixtures.

    python mockups/tools/split.py        # from the repository root

fixtures/capture.json + layouts.json  ->
  fixtures/api/*.json      each API answer, readable (what the pages fetched)
  fixtures/served/*.html   /dynamics and /machines as the server sent them
  fixtures/plugins/...     the plugins' static files the pages loaded
  fixtures/bundle.js       window.FIX: every API answer by path, the layouts and the capture time
"""

import json
import re
from pathlib import Path

FIX = Path(__file__).resolve().parent.parent / "fixtures"
cap = json.loads((FIX / "capture.json").read_text())
lay = json.loads((FIX / "layouts.json").read_text())
api = {}
for d in ("api", "served", "plugins"):
    (FIX / d).mkdir(exist_ok=True)
for key, r in cap.items():
    path = key.split("?")[0]
    if path in ("/dynamics", "/machines"):
        (FIX / "served" / (path[1:] + ".html")).write_text(r["body"])
    elif path.startswith("/plugins/"):
        f = FIX / "plugins" / path[len("/plugins/"):]
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(r["body"])
    elif path.startswith("/api/") and "json" in r["type"]:
        body = json.loads(r["body"])
        api[key] = body
        name = re.sub(r"[^A-Za-z0-9_.-]+", "_", key[len("/api/"):]).strip("_")
        (FIX / "api" / (name + ".json")).write_text(json.dumps(body, indent=1))
cap_at = lay.pop("capturedAt")
(FIX / "bundle.js").write_text("// generated by tools/split.py from capture.json: do not edit\nwindow.FIX = "
                               + json.dumps({"capturedAt": cap_at, "layouts": lay, "api": api}) + ";\n")
print(len(api), "api answers;", sorted(api))
