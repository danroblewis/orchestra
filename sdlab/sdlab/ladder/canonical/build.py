"""Write the canonical cases (cases/1NN-canonical-*.yaml) from recipes.yaml and the source models in
models/, through the PySD importer; refuse a model whose import does not reproduce PySD's own run.

    uv run --with pysd --with sympy python -m sdlab.ladder.canonical.build            # write them
    uv run --with pysd --with sympy python -m sdlab.ladder.canonical.build --check    # do the files match? (exit 1 if not)

A case is the imported model (stocks, flows, dt, inputs) plus the recipe's title, level, tags, tests,
source and the announced injections that keep it moving over the ladder's runs. The case files are
committed, so the ladder never needs pysd.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
MODELS = HERE / "models"
CASES = HERE.parent / "cases"
RECIPES = HERE / "recipes.yaml"
LONGEST = 2000                     # the ladder's long run (cases.LENGTHS): injections are written out to it


def recipes() -> list[dict]:
    return yaml.safe_load(RECIPES.read_text())


def _q(s: str) -> str:
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def case_text(r: dict, conv) -> str:
    from ..pysd_import import render

    lines = [f"# Generated by `python -m sdlab.ladder.canonical.build` from canonical/models/{r['model']} and",
             "# canonical/recipes.yaml; do not edit by hand (edit the recipe or the model and rebuild).",
             f"title: {_q(r['title'])}", f"level: {r['level']}", f"tags: [{', '.join(r['tags'])}]",
             f"tests: {_q(r['tests'])}", f"source: {_q(r['source'])}", f"seed: {int(r['id'][:3])}"]
    if r.get("variants"):                          # the case's own variants (2d: a signed oscillator is run without counting noise)
        lines.append("variants: " + yaml.safe_dump(r["variants"], default_flow_style=True, sort_keys=False).strip())
    lines.append(render(conv.parts, r.get("words")).rstrip("\n"))
    p = r.get("pulses")
    once = r.get("inject") or []                   # one-off injections, before the pulses
    if p or once:
        lines.append("injections:")
        for j in once:
            lines.append(f"  - {{t: {j['t']}, stock: {j['stock']}, amount: {j['amount']}}}")
    if p:
        for t in range(int(p["first"]), LONGEST + 1, int(p["every"])):
            for stock, amount in p["add"].items():
                lines.append(f"  - {{t: {t}, stock: {stock}, amount: {amount}}}")
    return "\n".join(lines) + "\n"


def build_one(r: dict) -> tuple[str, object, object]:
    """(case text, conversion, equivalence); raises if the import is blocked or differs from PySD."""
    from ..pysd_import import convert_checked

    conv, eq = convert_checked(MODELS / r["model"])               # (2d: convert, then signed where only the floor differs)
    if conv.text is None:
        raise ValueError(f"{r['id']}: {r['model']} does not convert: {'; '.join(conv.features)}")
    if not eq.ok:
        raise ValueError(f"{r['id']}: {r['model']} converts, but SD Lab's run differs from PySD's ({eq.reason}; {eq.error})")
    return case_text(r, conv), conv, eq


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="compare with the case files instead of writing them")
    ap.add_argument("ids", nargs="*", help="recipe ids (default: all)")
    a = ap.parse_args(argv)
    bad = 0
    for r in recipes():
        if a.ids and not any(r["id"].startswith(i) for i in a.ids):
            continue
        text, conv, eq = build_one(r)
        path = CASES / f"{r['id']}.yaml"
        worst = max(eq.error.values())
        if a.check:
            same = path.exists() and path.read_text() == text
            bad += not same
            print(f"{r['id']}: {'same' if same else 'DIFFERS'} (PySD vs SD Lab: max |difference| {worst:.2g})")
        else:
            path.write_text(text)
            print(f"{r['id']}: written (PySD vs SD Lab: max |difference| {worst:.2g}, dt {conv.dt}, {conv.steps} steps)")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
