"""Long runs of the examples' simulators, for testing discovery: generated on demand, cached locally.

    python tests/bench/datasets.py <example> [--steps N | --long] [--seed S]

prints the path of a JSON file {"example", "seed", "steps", "t", "levels", "eras", "counters"?}:
what SD Lab would have measured over that many steps (each simulator's `measured()`).

The cache lives outside the repository: $SDLAB_BENCH_CACHE, or ~/.cache/sdlab/bench. A file is
named by a hash of everything that decides its contents - the simulator's source files (every
.py in the example's machines folder), the length, the seed and this file's format version - so
changing a simulator rebuilds its datasets the next time they are asked for. Older versions are kept:
experiments in other worktrees may still be running against them. For an example generated by a system dynamics model, the hash also covers
its truth.model.json and the engine (sdlab/sdtruth.py, and the equations in sdlab/runner.py).
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import os
import sys
import time
from pathlib import Path

FORMAT = 2
EXAMPLES = Path(__file__).resolve().parents[2] / "sdlab" / "examples"


def cache_dir() -> Path:
    d = Path(os.environ.get("SDLAB_BENCH_CACHE") or Path.home() / ".cache" / "sdlab" / "bench")
    d.mkdir(parents=True, exist_ok=True)
    return d


def source_hash(example: str) -> str:
    h = hashlib.sha256(f"format {FORMAT}\n".encode())
    for p in sorted((EXAMPLES / example / "machines").glob("*.py")):
        h.update(p.name.encode() + b"\n" + p.read_bytes() + b"\n")
    # an example generated by a system dynamics model: the model and the engine that steps it
    truth_model = EXAMPLES / example / "truth.model.json"
    if truth_model.exists():
        for p in (truth_model, EXAMPLES.parent / "sdtruth.py", EXAMPLES.parent / "runner.py"):
            h.update(p.name.encode() + b"\n" + p.read_bytes() + b"\n")
    return h.hexdigest()[:16]


def load_sim(example: str):
    """The example's simulator, loaded by path (every example's is called sim.py, so it must not
    be left in sys.modules for the next one)."""
    machines = EXAMPLES / example / "machines"
    sys.path.insert(0, str(machines))
    sys.modules.pop("sim", None)
    try:
        spec = importlib.util.spec_from_file_location(f"bench_sim_{example}", machines / "sim.py")
        mod = importlib.util.module_from_spec(spec)
        sys.modules[spec.name] = mod                       # dataclasses look their module up by name
        spec.loader.exec_module(mod)
        return mod
    finally:
        sys.modules.pop("sim", None)
        sys.path.remove(str(machines))


def dataset(example: str, steps: int | None = None, seed: int | None = None, long: bool = False) -> Path:
    sim = load_sim(example)
    if not hasattr(sim, "measured"):
        raise SystemExit(f"{example}: its simulator has no measured(seed, steps) yet")
    seed = sim.SEED if seed is None else seed
    steps = (sim.LONG_STEPS if long else sim.STEPS) if steps is None else steps
    key = source_hash(example)
    path = cache_dir() / f"{example}-{key}-s{seed}-n{steps}.json"
    if path.exists():
        return path
    began = time.time()
    data = sim.measured(seed=seed, steps=steps)
    if hasattr(sim, "TRUTH"):                                 # generated by an SD model: every stock's level too,
        data["all_levels"] = sim.run(seed, steps)["levels"]   # so the true model can be run from any moment
    out = {"example": example, "seed": seed, "steps": steps, "source": key, "seconds": round(time.time() - began, 2), **data}
    tmp = path.with_suffix(f".{os.getpid()}.tmp")
    tmp.write_text(json.dumps(out, separators=(",", ":")))
    tmp.replace(path)
    return path


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("example")
    ap.add_argument("--steps", type=int)
    ap.add_argument("--long", action="store_true", help="the simulator's LONG_STEPS")
    ap.add_argument("--seed", type=int)
    a = ap.parse_args()
    print(dataset(a.example, a.steps, a.seed, a.long))


if __name__ == "__main__":
    main()
